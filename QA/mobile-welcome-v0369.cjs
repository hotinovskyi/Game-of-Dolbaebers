const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const asset = path.join(root, 'assets', 'welcome-symmetrical-v0369.jpg');
assert.match(html, /<title>Game of Dolbaebers · 0\.36\.9<\/title>/);
assert.equal((html.match(/id="welcomeContinue"/g) || []).length, 1, 'Должна быть ровно одна настоящая кнопка старта');
assert.match(html, /src="assets\/welcome-symmetrical-v0369\.jpg"/);
assert.match(html, /aria-label="Начать игру"/);
const welcomeMarkup = html.slice(html.indexOf('<div class=\"welcome-overlay\"'), html.indexOf('<div id=\"actionReport\"'));
assert.ok(welcomeMarkup.length > 0, 'Разметка стартового экрана должна существовать');
assert.doesNotMatch(welcomeMarkup, /welcome-splash-title|welcome-splash-kicker|welcome-start-button/);
assert.match(html, /#welcomeOverlay\.show \.welcome-scene-image\{[\s\S]*?object-fit:fill/);
assert.match(html, /#welcomeOverlay\.show \.welcome-start-hit\{[\s\S]*?left:6\.5%[\s\S]*?top:70\.5%[\s\S]*?width:87%/);
assert.match(html, /@keyframes welcomeSceneIn/);
assert.match(html, /@keyframes welcomeLightDrift/);
assert.match(html, /@keyframes welcomeButtonShine/);
assert.match(html, /@media\(prefers-reduced-motion:reduce\)/);
assert.match(html, /const continueFromWelcome=\(\)=>\{\$\('#welcomeOverlay'\)\.classList\.remove\('show'\);\$\('#heroSelectOverlay'\)\.classList\.add\('show'\);\};\$\('#welcomeContinue'\)\.addEventListener\('click',continueFromWelcome\);/);
assert.ok(fs.existsSync(asset), 'Файл стартовой иллюстрации должен быть в сборке');
assert.ok(fs.statSync(asset).size > 100000 && fs.statSync(asset).size < 1500000, 'Иллюстрация должна быть оптимизирована для мобильной загрузки');
console.log('0.36.9 mobile welcome: single accessible CTA, full portrait art, responsive ratio, animations, reduced motion, existing hero-pick transition: PASS');
